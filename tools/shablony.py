def nov():
    d = Document()
    st = d.styles['Normal']; st.font.name = 'Times New Roman'; st.font.size = Pt(12)
    for s in d.sections:
        s.left_margin, s.right_margin, s.top_margin, s.bottom_margin = Cm(2.5), Cm(1.5), Cm(2), Cm(2)
        p = s.footer.paragraphs[0]; p.text = PODVAL; p.runs[0].font.size = Pt(8)
    return d


def abz(d, t='', bold=False, center=False, right=False, size=None):
    p = d.add_paragraph(); r = p.add_run(t); r.bold = bold
    if size: r.font.size = Pt(size)
    if center: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if right: p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_after = Pt(4)
    return p


def tabl(d, shapka, stroki, shir=None):
    t = d.add_table(rows=1, cols=len(shapka)); t.style = 'Table Grid'
    for i, h in enumerate(shapka):
        c = t.rows[0].cells[i]; c.text = ''; c.paragraphs[0].add_run(h).bold = True
    for s in stroki:
        cells = t.add_row().cells
        for i, v in enumerate(s): cells[i].text = v
    if shir:
        for row in t.rows:
            for i, w in enumerate(shir): row.cells[i].width = Cm(w)
    for row in t.rows:
        for c in row.cells:
            for p in c.paragraphs:
                for r in p.runs: r.font.size = Pt(10)
    d.add_paragraph()
    return t


